#!/usr/bin/env node
// The DWARF line census: what a debugger is given, counted in both directions.
//
// # The two holes
//
// A debug build can fail a source breakpoint in two different ways, and a
// report that counts only one of them is half a measurement:
//
//   `unreachable_lines`   A source line the DWARF *mentions* but gives no
//                         address range. The line table has a row for it, and
//                         every row for it has zero span — so there is no
//                         instruction a debugger can bind that line to. This is
//                         the "breakpoint is pending forever" class.
//
//   `unpaired_addresses`  A line-table address that falls inside no compile
//                         unit's range. The row exists and names a line, but the
//                         address it names is not one the unit claims, which is
//                         the `unable to resolve a line table file address …
//                         back to a compile unit` message. This is the class
//                         where a breakpoint binds to an address the debugger
//                         then cannot describe.
//
// Both are counted per file and in total, and every mentioned line also gets
// its shape — how many locations and how many bytes they cover — so a change
// that leaves a line reachable but moves its boundaries is still visible.
//
// # What it reads, and what it refuses to read
//
// `.debug_info`, `.debug_abbrev`, `.debug_line`, `.debug_ranges`, directly out
// of the module (`lib/dwarf-reader.js`). **Not `.wasm.map`**: the debugger never
// opens it, so a source map that agrees proves nothing, and a manifest built
// from it would be measuring the compiler against its own opinion.
//
// # Determinism
//
// Same bytes in, same text out: files sorted by path, lines by number,
// addresses by value. Nothing here reads a clock, a pid, or an environment
// variable. `--check` can therefore be a gate, and the committed manifest can
// be diffed.
//
// # Usage
//
//   node tests/debug/census.js <module.wasm> [...]         # manifest to stdout
//   node tests/debug/census.js --out <file> <module...>    # write a manifest
//   node tests/debug/census.js --check <file> <module...>  # ratchet
//
// `--check` is a **ratchet**: fewer holes is free, a new hole or a line whose
// span shrank is a failure. A manifest is regenerated by `--out`, and the
// commit that regenerates it owes a one-line reason for every entry that got
// worse — which is what a diff shows and a blanket regeneration hides.

import fs from "node:fs";
import path from "node:path";

import { readDwarf } from "./lib/dwarf-reader.js";

const FORMAT = "dwarf-census v1";

function parseArgs(argv) {
  const args = { modules: [], out: null, check: null };
  for (let i = 0; i < argv.length; ++i) {
    const arg = argv[i];
    if (arg === "--out") args.out = argv[++i];
    else if (arg === "--check") args.check = argv[++i];
    else if (arg.startsWith("--")) throw new Error(`unknown argument ${arg}`);
    else args.modules.push(arg);
  }
  // A **directory** means "every module in it", sorted — so one flag can name a
  // whole build tree without a shell glob (`sh` expands one, `cmd` does not, and
  // a gate that only runs on two of the three platforms is not a gate).
  const expanded = [];
  for (const entry of args.modules) {
    if (fs.existsSync(entry) && fs.statSync(entry).isDirectory()) {
      const found = fs
        .readdirSync(entry)
        .filter((name) => name.endsWith(".wasm"))
        .sort()
        .map((name) => path.join(entry, name));
      if (found.length === 0) throw new Error(`no .wasm files in ${entry}`);
      expanded.push(...found);
    } else {
      expanded.push(entry);
    }
  }
  args.modules = expanded;
  // The artifacts are built by the engine repository's harness, not here, so a
  // caller that does not name them gets the environment's answer. There is no
  // guessed default: a path this file invented would measure whatever happened
  // to sit at it, and that is how a census stops describing the compiler.
  if (args.modules.length === 0 && process.env.TENSION_DEBUG_ARTIFACTS) {
    args.modules.push(process.env.TENSION_DEBUG_ARTIFACTS);
    const again = parseArgs([process.env.TENSION_DEBUG_ARTIFACTS]);
    args.modules = again.modules;
  }
  if (args.modules.length === 0) {
    throw new Error(
      "usage: census.js [--out <file> | --check <file>] <module.wasm | dir> ...\n" +
        "       or set TENSION_DEBUG_ARTIFACTS to the directory the conformance matrix builds:\n" +
        "       node scripts/build-test-programs.mjs --debug   # in the Tension checkout\n" +
        "       TENSION_DEBUG_ARTIFACTS=<repo>/tension-core/tests/programs/build/debug"
    );
  }
  return args;
}

/**
 * The census of one module.
 *
 * The two questions are asked of the same row list, so they cannot disagree
 * about which rows exist.
 */
export function census(bytes) {
  const dwarf = readDwarf(bytes);
  if (!dwarf) {
    return {
      units: 0,
      files: new Map(),
      unreachable: 0,
      unpaired: 0,
      lines: [],
      addresses: [],
    };
  }

  // Every range any compile unit claims, so an address can be asked "is this
  // anybody's?" once rather than per row.
  const unitRanges = [];
  for (const unit of dwarf.units) {
    if (unit.ranges.length > 0) {
      for (const [low, high] of unit.ranges) unitRanges.push([low, high]);
    } else if (unit.lowPc != null && unit.highPc != null && unit.highPc > unit.lowPc) {
      unitRanges.push([unit.lowPc, unit.highPc]);
    }
  }
  const paired = (address) => unitRanges.some(([low, high]) => address >= low && address < high);

  /** file → line → { locations, bytes } */
  const byLine = new Map();
  const mentioned = new Map();
  const unpairedRows = [];

  const note = (file, line) => {
    if (!byLine.has(file)) byLine.set(file, new Map());
    const lines = byLine.get(file);
    if (!lines.has(line)) lines.set(line, { locations: 0, bytes: 0 });
    return lines.get(line);
  };
  const mention = (file, line) => {
    if (!mentioned.has(file)) mentioned.set(file, new Set());
    mentioned.get(file).add(line);
    note(file, line);
  };

  for (const [index, unit] of dwarf.units.entries()) {
    const table = dwarf.line(unit);
    const fileOf = (indexInTable) => {
      // The line program's file numbers are 1-based; `0` is "the primary
      // source", which this producer never uses, so it is reported as itself
      // rather than silently folded into file 1.
      if (indexInTable <= 0) return "<primary>";
      return table.files[indexInTable - 1] ?? `<file ${indexInTable}>`;
    };

    for (const sequence of table.sequences) {
      const rows = sequence.rows;
      for (let i = 0; i < rows.length; ++i) {
        const row = rows[i];
        const file = fileOf(row.file);
        if (row.isEnd) continue;
        mention(file, row.line);
        // The span a row owns is up to the next row in the same sequence — or
        // up to the end-sequence row, whose address is the sequence's end. A
        // row that shares its address with the next one owns no bytes, which is
        // exactly the "mentioned but unreachable" case.
        const next = rows[i + 1];
        const span = next ? next.address - row.address : 0;
        if (span > 0) {
          const entry = note(file, row.line);
          entry.locations += 1;
          entry.bytes += span;
        }
        if (!paired(row.address)) {
          unpairedRows.push({ address: row.address, file, line: row.line });
        }
      }
    }

    // Declarations name a source position too, and a line a symbol is declared
    // on with no row at all is a hole of the same kind: the DWARF mentions it,
    // and nothing can bind it.
    for (const { file, line } of dwarf.declLines(index)) {
      mention(fileOf(file), line);
    }
  }

  const files = new Map();
  const lines = [];
  let unreachable = 0;
  for (const file of [...byLine.keys()].sort()) {
    const fileLines = byLine.get(file);
    let fileUnreachable = 0;
    let fileLocations = 0;
    let fileBytes = 0;
    for (const line of [...fileLines.keys()].sort((a, b) => a - b)) {
      const entry = fileLines.get(line);
      const isUnreachable = entry.locations === 0;
      if (isUnreachable) {
        ++fileUnreachable;
        ++unreachable;
      }
      fileLocations += entry.locations;
      fileBytes += entry.bytes;
      lines.push({
        file,
        line,
        locations: entry.locations,
        bytes: entry.bytes,
        unreachable: isUnreachable,
      });
    }
    files.set(file, {
      lines: fileLines.size,
      unreachable: fileUnreachable,
      locations: fileLocations,
      bytes: fileBytes,
    });
  }

  unpairedRows.sort((a, b) => a.address - b.address || a.file.localeCompare(b.file) || a.line - b.line);

  return {
    units: dwarf.units.length,
    files,
    unreachable,
    unpaired: unpairedRows.length,
    lines,
    addresses: unpairedRows,
  };
}

/** The manifest text: one module, sorted throughout. */
export function manifest(entries) {
  const out = [`# ${FORMAT}`];
  let totalUnreachable = 0;
  let totalUnpaired = 0;
  let totalLines = 0;
  for (const { name, result } of entries) {
    out.push(`module ${name}`);
    out.push(`units ${result.units}`);
    for (const [file, summary] of result.files) {
      out.push(
        `file ${file} lines ${summary.lines} unreachable ${summary.unreachable} ` +
          `locations ${summary.locations} bytes ${summary.bytes}`
      );
    }
    for (const line of result.lines) {
      out.push(
        `line ${line.file}:${line.line} locations ${line.locations} bytes ${line.bytes}` +
          (line.unreachable ? " unreachable" : "")
      );
    }
    for (const address of result.addresses) {
      out.push(`addr 0x${address.address.toString(16)} ${address.file}:${address.line} unpaired`);
    }
    out.push(`module-total unreachable_lines ${result.unreachable} unpaired_addresses ${result.unpaired}`);
    totalUnreachable += result.unreachable;
    totalUnpaired += result.unpaired;
    totalLines += result.lines.length;
  }
  out.push(
    `total modules ${entries.length} lines ${totalLines} ` +
      `unreachable_lines ${totalUnreachable} unpaired_addresses ${totalUnpaired}`
  );
  return `${out.join("\n")}\n`;
}

/**
 * The ratchet: is `next` no worse than `committed`?
 *
 * "Worse" is a line that got more unreachable, a file that gained unreachable
 * lines, an address that gained an unpaired entry, or a total that went up.
 * Improvements are reported and allowed — that is the direction a ratchet is
 * for. The comparison is by key, so a reordering is not a change.
 */
export function ratchet(committed, next) {
  const read = (text) => {
    const lines = new Map();
    let unreachable = 0;
    let unpaired = 0;
    for (const raw of text.split("\n")) {
      const line = raw.trim();
      if (!line || line.startsWith("#")) continue;
      const total = /^total modules (\d+) lines (\d+) unreachable_lines (\d+) unpaired_addresses (\d+)$/.exec(line);
      if (total) {
        unreachable = Number(total[3]);
        unpaired = Number(total[4]);
        continue;
      }
      const perLine = /^line (.+):(\d+) locations (\d+) bytes (\d+)( unreachable)?$/.exec(line);
      if (perLine) {
        lines.set(`${perLine[1]}:${perLine[2]}`, {
          locations: Number(perLine[3]),
          bytes: Number(perLine[4]),
          unreachable: Boolean(perLine[5]),
        });
      }
    }
    return { lines, unreachable, unpaired };
  };
  const before = read(committed);
  const after = read(next);
  const worsened = [];
  const improved = [];
  for (const [key, value] of after.lines) {
    const was = before.lines.get(key);
    if (!was) {
      // A new entry: it is only a regression when it is a hole. A line that
      // appeared with locations is new work measured, not worse.
      if (value.unreachable) worsened.push(`${key}: new unreachable line`);
      continue;
    }
    if (!was.unreachable && value.unreachable) worsened.push(`${key}: became unreachable`);
    else if (was.bytes > 0 && value.bytes < was.bytes) {
      worsened.push(`${key}: span shrank ${was.bytes} -> ${value.bytes}`);
    } else if (was.bytes > value.bytes) improved.push(`${key}: span ${was.bytes} -> ${value.bytes}`);
  }
  for (const [key, value] of before.lines) {
    if (!value.unreachable) continue;
    const now = after.lines.get(key);
    if (now && !now.unreachable) improved.push(`${key}: reachable now`);
  }
  if (after.unreachable > before.unreachable) {
    worsened.push(`total unreachable_lines ${before.unreachable} -> ${after.unreachable}`);
  } else if (after.unreachable < before.unreachable) {
    improved.push(`total unreachable_lines ${before.unreachable} -> ${after.unreachable}`);
  }
  if (after.unpaired > before.unpaired) {
    worsened.push(`total unpaired_addresses ${before.unpaired} -> ${after.unpaired}`);
  } else if (after.unpaired < before.unpaired) {
    improved.push(`total unpaired_addresses ${before.unpaired} -> ${after.unpaired}`);
  }
  return { ok: worsened.length === 0, worsened, improved };
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const entries = [];
  for (const module of args.modules) {
    const bytes = fs.readFileSync(module);
    entries.push({ name: path.basename(module), result: census(bytes) });
  }
  const text = manifest(entries);

  if (args.out) {
    fs.mkdirSync(path.dirname(args.out), { recursive: true });
    fs.writeFileSync(args.out, text);
    process.stdout.write(`${args.out}: ${text.split("\n").length - 1} lines\n`);
    return;
  }
  if (args.check) {
    const committed = fs.readFileSync(args.check, "utf8");
    const verdict = ratchet(committed, text);
    for (const line of verdict.improved) console.log(`improved ${line}`);
    for (const line of verdict.worsened) console.log(`WORSE ${line}`);
    console.log(
      verdict.ok
        ? `census: ${args.check} holds (${verdict.improved.length} improved, 0 worse)`
        : `census: ${args.check} is worse in ${verdict.worsened.length} place(s)`
    );
    if (!verdict.ok) process.exitCode = 1;
    return;
  }
  process.stdout.write(text);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    main();
  } catch (error) {
    console.error(`census: ${error && error.message ? error.message : error}`);
    process.exitCode = 2;
  }
}
